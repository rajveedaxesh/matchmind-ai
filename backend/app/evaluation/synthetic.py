"""Synthetic benchmark: expanded fictional candidate pool + rule-based graded relevance labels.

IMPORTANT - what these labels are (and are not)
-----------------------------------------------
Labels are generated by a transparent rule over *latent ground truth* the matcher never sees:
  * the candidate's true role family and TRUE skill set (the visible profile drops ~15% of true skills
    and adds 0-2 unrelated "noise" skills, imitating an imperfect résumé);
  * seeded Gaussian noise imitating annotator disagreement.
They share *concepts* with the hybrid scorer (skills, role, experience), so the hybrid engine has a
structural advantage over a text-only baseline. The benchmark therefore demonstrates the evaluation
pipeline and the value of structured signals under these assumptions - it is NOT evidence of
real-world hiring accuracy.
"""
from __future__ import annotations

import random
from dataclasses import dataclass, field

from ..data.adapters import to_candidate_profile, to_job_posting
from ..data.candidates import SEED_CANDIDATES
from ..data.families import FAMILIES, LOCATIONS, families_adjacent
from ..data.jobs import SEED_JOBS
from ..ml.skills import normalize_skills
from ..ml.types import CandidateProfile, JobPosting

LABEL_DEFINITION = (
    "grade = 0.35*role_family_match (1 same, 0.5 adjacent, 0 otherwise) + 0.50*true_required_skill_coverage "
    "+ 0.15*experience_in_loose_range + Gaussian noise (sd 0.05); "
    "grade 3 if >= 0.80, 2 if >= 0.62, 1 if >= 0.40, else 0. Relevant (for Precision/Recall/MRR) means grade >= 2."
)
GRADE_CUTS = ((0.80, 3), (0.62, 2), (0.40, 1))


@dataclass
class EvalJob:
    posting: JobPosting
    family: str


@dataclass
class EvalCandidate:
    profile: CandidateProfile
    family: str
    true_skills: tuple[str, ...]
    synthetic_generated: bool = False


@dataclass
class EvalPopulation:
    jobs: list[EvalJob]
    candidates: list[EvalCandidate]
    labels: dict[tuple[int, int], int] = field(default_factory=dict)  # (job_id, candidate_id) -> grade
    seed: int = 42
    generated_per_family: int = 0


def relevance_grade(
    job_family: str,
    job_required: tuple[str, ...],
    job_min_years: float | None,
    job_max_years: float | None,
    cand_family: str,
    cand_true_skills: tuple[str, ...],
    cand_years: float,
    seed: int,
    job_id: int,
    cand_id: int,
) -> int:
    if cand_family == job_family:
        fam = 1.0
    elif families_adjacent(cand_family, job_family):
        fam = 0.5
    else:
        fam = 0.0
    required = normalize_skills(job_required)
    have = set(normalize_skills(cand_true_skills))
    coverage = sum(1 for s in required if s in have) / len(required) if required else 0.0
    lo = 0.0 if job_min_years is None else float(job_min_years)
    hi = float("inf") if job_max_years is None else float(job_max_years)
    exp_ok = 1.0 if (lo - 1.0) <= cand_years <= (hi + 3.0) else 0.0
    value = 0.35 * fam + 0.50 * coverage + 0.15 * exp_ok
    value += random.Random(f"{seed}:{job_id}:{cand_id}").gauss(0.0, 0.05)
    for cut, grade in GRADE_CUTS:
        if value >= cut:
            return grade
    return 0


def _generate_candidates(rng: random.Random, per_family: int, start_id: int) -> list[EvalCandidate]:
    all_core = {k: set(f["core"]) for k, f in FAMILIES.items()}
    out: list[EvalCandidate] = []
    next_id = start_id
    for fam_key, fam in FAMILIES.items():
        outside = sorted(set().union(*(v for k, v in all_core.items() if k != fam_key)))
        for _ in range(per_family):
            level = rng.choices(["junior", "mid", "senior"], weights=[0.25, 0.5, 0.25])[0]
            years = {"junior": rng.randint(0, 2), "mid": rng.randint(3, 6), "senior": rng.randint(7, 12)}[level]
            extras = rng.sample(fam["extra"], k=min(len(fam["extra"]), rng.randint(2, 5)))
            true_skills = list(dict.fromkeys(fam["core"] + extras))
            visible = [s for s in true_skills if rng.random() > 0.15]
            noise_pool = [s for s in outside if s not in true_skills]
            visible += rng.sample(noise_pool, k=rng.randint(0, 2))
            title = rng.choice(fam["titles"])
            prefix = "" if level == "mid" or title.lower().startswith("senior") else ("Junior " if level == "junior" else "Senior ")
            cities = rng.sample([loc.split(",")[0] for loc in LOCATIONS], k=rng.randint(1, 2))
            modes = rng.choice([["remote"], ["hybrid"], ["remote", "hybrid"], ["onsite", "hybrid"], []])
            profile = CandidateProfile(
                id=next_id,
                headline=f"{prefix}{title}",
                summary=" ".join(rng.sample(fam["blurbs"], 2)),
                skills=tuple(visible),
                years_experience=float(years),
                desired_titles=(title,),
                preferred_locations=tuple(cities + (["Remote"] if "remote" in modes else [])),
                preferred_work_modes=tuple(modes),
                open_to_relocation=rng.random() < 0.3,
            )
            out.append(EvalCandidate(profile, fam_key, tuple(true_skills), synthetic_generated=True))
            next_id += 1
    return out


def build_population(seed: int = 42, generated_per_family: int = 8) -> EvalPopulation:
    """Hand-written seed jobs/candidates plus ``generated_per_family`` generated candidates per family."""
    if generated_per_family < 0 or generated_per_family > 30:
        raise ValueError("generated_per_family must be between 0 and 30")
    jobs = [EvalJob(to_job_posting(d, job_id=i + 1), d["role_family"]) for i, d in enumerate(SEED_JOBS)]
    cands = [
        EvalCandidate(to_candidate_profile(d, candidate_id=i + 1), d["family"], tuple(d["skills"]))
        for i, d in enumerate(SEED_CANDIDATES)
    ]
    rng = random.Random(seed)
    cands += _generate_candidates(rng, generated_per_family, start_id=1000)
    labels: dict[tuple[int, int], int] = {}
    for j in jobs:
        for c in cands:
            labels[(j.posting.id, c.profile.id)] = relevance_grade(
                j.family, j.posting.required_skills, j.posting.min_years, j.posting.max_years,
                c.family, c.true_skills, c.profile.years_experience or 0.0, seed, j.posting.id, c.profile.id,
            )
    return EvalPopulation(jobs, cands, labels, seed, generated_per_family)
